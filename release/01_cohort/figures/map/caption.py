#!/usr/bin/env python3
"""caption.py — write the map caption from the tables themselves.

    python release/01_cohort/figures/map/caption.py

Reads  map_points.tsv, map_summary.tsv  (prep_map.py)
Writes map_caption.txt

Nothing below is prose with numbers typed into it. The narrative is a template and every
figure in it is read at write time, for the reason the crop-map caption records: a
caption hand-patched across a session drifts, and a claim nobody can recompute is one
nobody can check.
"""

import collections
import csv
import sys
import textwrap
from pathlib import Path

MODULE = Path(__file__).resolve().parents[2]    # release/01_cohort
FIG = Path(__file__).resolve().parent           # this figure's own directory


def reflow(text, width=86):
    """Wrap the prose paragraphs and leave the indented blocks alone.

    The template is written at a fixed width and every number interpolated into it
    changes the line lengths, so what is written out is ragged unless it is rewrapped
    after the substitution rather than before.
    """
    out = []
    for i, block in enumerate(text.split("\n\n")):
        # Block 0 is the title and its figure line, which are two lines on purpose.
        # An indented block is a table. Everything else is prose and gets rewrapped.
        if i == 0 or block.startswith("  ") or len(block) < width:
            out.append(block)
            continue
        out.append(textwrap.fill(" ".join(block.split()), width=width))
    return "\n\n".join(out)


def read(path):
    with open(path, newline="", encoding="utf-8") as fh:
        return list(csv.DictReader(fh, delimiter="\t"))


def summary_values():
    return {r["measure"]: int(r["value"]) for r in read(FIG / "map_summary.tsv")}


def map_caption():
    s = summary_values()
    pts = read(FIG / "map_points.tsv")
    loc = [p for p in pts if p["placement"] == "Locality"]
    ctry = sorted([p for p in pts if p["placement"] == "Country"],
                  key=lambda p: -int(p["runs"]))
    prec = {k.replace("locality runs at precision: ", ""): v
            for k, v in s.items() if k.startswith("locality runs at precision")}
    biggest = max(loc, key=lambda p: int(p["runs"]))
    top = ", ".join(f"{p['location']} {p['runs']}" for p in ctry[:3])

    return reflow(f"""Where the Cohort Was Collected
Caption for map.{{png,pdf}} and map_europe.{{png,pdf}}, key in map_legend.png

GENERATED by figures/map/caption.py — do not hand-edit, the numbers will drift.


FULL CAPTION

Collection origin of the field wheat cohort: {s['field-wheat runs in cohort']:,} runs,
of which {s['drawn at a locality']:,} are drawn at a named place and
{s['drawn at a country centroid']} at a country centroid.

Only field-collected Triticum is plotted. Lab material and off-host runs are excluded
even where they carry coordinates, because an isolate deposit records where its pustule
was collected, not where anything was sampled. The test is the same one that colours a
run green in the network figure, so the two panels describe the same samples.

Green circles are {len(loc)} named places. Blue circles are {len(ctry)} country
centroids, carrying the runs whose papers record a country and nothing finer; the
largest are {top}.

A BLUE CIRCLE IS NOT A COLLECTION SITE. It states WHICH COUNTRY and sits at the
centroid of that country's largest landmass polygon, a place nobody sampled.

Point diameter scales with the square root of the runs at that point, so area is
proportional to count and the key can be read off. Points are semi-transparent, so
overlapping places compound into darker patches. The largest named place is
{biggest['location']} with {biggest['runs']} runs; the key runs to 65 because the
largest marks on the map are blue, not green.

THE BIGGEST MARKS ARE THE LEAST PRECISE, which is the opposite of what a reader
expects. Country circles carry up to {max(int(p['runs']) for p in ctry)} runs and named
places at most {max(int(p['runs']) for p in loc)}.

map_europe.{{png,pdf}} is the second image: Europe, North Africa and the Near East,
19W to 38E and 27N to 58N, where
{sum(1 for p in pts if -19 <= float(p['lon']) <= 38 and 27 <= float(p['lat']) <= 58)}
of the {len(pts)} points sit and where the world view is one blot. It is cropped to its
contents rather than to the region, and it is drawn to the SAME size scale as the world
map. Both are rendered at the size they are placed at, so a mark of a given size means
the same number of runs in both and the key serves both.


WHAT IS NOT SHOWN

{s['not drawn: no usable place']} runs name no place at all and are absent from the
map while remaining in every count elsewhere.

The {s['drawn at a country centroid']} country-level runs are not a geocoding failure.
Each was pursued to the source: three supplementary tables were read end to end
(Lewis et al. 2024 Dataset S2, Hubbard et al. 2015, and Table S13 of the 2025 brown
rust study, joined run by run through ENA's secondary accessions), and each records a
country and nothing finer for exactly these samples. Where a finer value existed it was
taken — five Western Australian runs were placed at Kulin, Corrigin, Goomalling and
Wongan Hills from Table 1 of 10.3390/v15020401, matched on the BioSample isolate field.

Named places are placed at several precisions, recorded per run in
curated_attributes.tsv: {', '.join(f'{v} {k}' for k, v in prec.items())}.


SHORT CAPTION

Collection origin of {s['field-wheat runs in cohort']:,} field wheat runs. Green
circles are {s['drawn at a locality']:,} runs at {len(loc)} named places; blue circles
are {s['drawn at a country centroid']} runs at {len(ctry)} country centroids, drawn at
a place nobody sampled because their papers record no finer location. Point area is
proportional to run count. {s['not drawn: no usable place']} runs name no place and are
absent. The European window is drawn separately, in map_europe.{{png,pdf}}.


SOURCES

  figure   release/01_cohort/figures/map/map.R  (map and map_europe)
  prep     release/01_cohort/figures/map/prep_map.py
  caption  release/01_cohort/figures/map/caption.py
  data     map_points.tsv, map_summary.tsv
  geocode  research/01_literature/retrieve/geocode_localities.py
  supps    data/raw/supplements/
""")



def main():
    (FIG / "map_caption.txt").write_text(map_caption(), encoding="utf-8")
    print(f"wrote {FIG / 'map_caption.txt'}")


if __name__ == "__main__":
    main()
