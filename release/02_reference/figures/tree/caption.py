#!/usr/bin/env python3
"""caption.py — the caption for panel B, written from the prepared tree tables.

    python release/02_reference/figures/tree/caption.py

Reads  tree_tips.tsv, tree_clades.tsv            (beside this script)
Writes tree_caption.txt

Nothing here is prose-with-numbers-typed-in: the narrative is a template and every figure in
it is read at write time. Rerun after prep_tree.py.
"""

import sys
from collections import defaultdict
from pathlib import Path

HERE = Path(__file__).resolve().parents[2]          # release/02_reference
FIG = Path(__file__).resolve().parent
sys.path.insert(0, str(HERE / "scripts"))
from _caption import rd, para, write                # noqa: E402

# Must match figures/tree/tree_legend.R and prep_tree.py CATEGORIES.
LABEL = {"wheat_pathogen": "wheat pathogen",
         "onwheat_pathogen": "pathogen elsewhere, recorded on wheat",
         "onwheat_resident": "non-pathogen, recorded on wheat",
         "plant_pathogen": "pathogen elsewhere, not on wheat",
         "plant_resident": "non-pathogen, not on wheat"}


def main():
    tips = rd(FIG / "tree_tips.tsv")
    n = len(tips)
    cat = defaultdict(int)
    for t in tips:
        cat[t["category"]] += 1
    assert set(cat) <= set(LABEL), f"unlabelled category: {set(cat) - set(LABEL)}"

    full = sum(1 for t in tips if float(t["annotation_ratio"]) >= 0.999)
    part = n - full
    top = max(int(t["n_genomes"]) for t in tips)
    single = sum(1 for t in tips if int(t["n_genomes"]) == 1)
    # tree.R draws an arc only for classes with >= LABEL_MIN members, so the caption has to
    # apply the same floor or it reports every class in the table instead of every arc drawn.
    LABEL_MIN = 40
    clades = [r for r in rd(FIG / "tree_clades.tsv")
              if r["rank"] == "class" and int(r["n_species"]) >= LABEL_MIN]

    key = "\n".join(f"  {LABEL[k]:<42}{cat[k]:>6,}" for k in LABEL if cat[k])

    write(FIG / "tree_caption.txt", para(
        "The Reference Database, by Taxonomy",
        "Caption for tree.png (panel B), keyed by tree_legend.png.",
        "",
        "GENERATED by caption.py — do not hand-edit, the numbers will drift.",
        "",
        "The key is a separate file so the fan can be placed and scaled independently of it.",
        "",
        "",
        "FULL CAPTION",
        "",
        f"Taxonomic distribution of the {n:,} reference taxa that have both a USDA record "
        f"and a gene model, drawn as a circular cladogram built from the NCBI taxonomy. IT "
        f"IS A TAXONOMY, NOT A PHYLOGENY: radius encodes rank, from kingdom at the centre "
        f"to species at the rim, and carries no information about divergence. Branch "
        f"lengths are not evolutionary distances and must not be read as any.",
        "",
        f"Only the observation rows of panel A appear. Congeners are excluded, because a "
        f"taxon admitted so the classifier has a competitor is never reported as a "
        f"detection, and taxa with no gene model are excluded because they contribute no "
        f"CDS. These {n:,} are the taxa the database is actually built from.",
        "",
        f"Bar length is the number of genome assemblies for that taxon on a log scale, with "
        f"dotted gridlines and numerals at 1, 10 and 100. The spread is wide: {single:,} of "
        f"{n:,} taxa have a single assembly and the largest has {top:,}.",
        "",
        "Bar colour is the taxon's cell in panel A, using the same five colours, so a hue "
        "means the same thing in both panels:",
        "",
        key,
        "",
        f"The inner ring at the base of each bar is the share of that taxon's assemblies "
        f"carrying a gene model: pale where all of them do, dark purple where few do. "
        f"{full:,} of {n:,} taxa are fully annotated and {part:,} are not. The dark "
        f"segments are the gene-prediction worklist, because those are genomes already "
        f"deposited whose CDS the database cannot currently use.",
        "",
        f"The {len(clades)} arcs outside the bars mark the taxonomic classes with at least "
        f"{LABEL_MIN} members: " + ", ".join(sorted(c["clade"] for c in clades)) + ". They "
        f"are reading aids for position in the tree, not a result; the smaller classes are "
        f"present as tips but carry no arc.",
        "",
        "",
        "HOW TO READ IT",
        "",
        "The panel is mostly one pale colour on purpose. The reference is a community, and "
        "the organisms anyone has studied are a sliver of it: the pathogens are the few "
        "bright spikes against a pale field, and they are tallest where they are "
        "hyper-sequenced, which is a statement about research attention and not about "
        "abundance in a field.",
        "",
        "",
        "WHAT IS NOT SHOWN",
        "",
        "Nothing here is a detection. Bar length counts deposited assemblies, so a tall bar "
        "means a well-sequenced organism, never an abundant or a frequently detected one.",
        "",
        "Taxa with no gene model are absent from this panel but remain in the database "
        "scope and in panel A, where the gap between the Asm. and CDS rows measures them.",
        "",
        "",
        "SHORT CAPTION",
        "",
        f"Taxonomic distribution of the {n:,} reference taxa carrying both a USDA record "
        f"and a gene model, on a circular NCBI cladogram where radius is taxonomic rank, "
        f"not divergence. Bar length is the taxon's assembly count on a log10 scale; bar "
        f"colour is its cell in panel A ("
        # semicolons, because the labels themselves contain commas
        + "; ".join(f"{LABEL[k]} {cat[k]:,}" for k in LABEL if cat[k]) +
        f"). The inner ring is the share of that taxon's assemblies carrying a gene model, "
        f"pale where all do and dark purple where few do ({full:,} of {n:,} fully "
        f"annotated). Arcs mark the {len(clades)} taxonomic classes with at least "
        f"{LABEL_MIN} members. Congeners are excluded, being classifier competitors that "
        f"are never reported.",
    ))


if __name__ == "__main__":
    main()
