#!/usr/bin/env python3
"""caption.py — the caption for the purpose test, written from the data.

    python release/03_classify/figures/resolution/caption.py

Reads  resolution_summary.tsv, resolution_ticks.tsv   (beside this script)
       ../../../02_reference/data/curation/extra_cds_db2.tsv   the tier of each prediction
Writes resolution_caption.txt

Every number is read at write time. See crypt-figure-caption-discipline.
"""

import collections
import csv
import sys
from pathlib import Path

HERE = Path(__file__).resolve().parents[2]              # release/03_classify
FIG = Path(__file__).resolve().parent
sys.path.insert(0, str(HERE.parent / "02_reference/scripts"))
from _caption import rd, para, write                    # noqa: E402
sys.path.insert(0, str(FIG))
from prep_resolution import LIN                         # noqa: E402

EXTRA = HERE.parent / "02_reference/data/curation/extra_cds_db2.tsv"
DET = {a: HERE / f"data/outputs/detections_{a}.tsv" for a in ("db1p", "db2")}


def main():
    sm = {r["bucket"]: r for r in rd(FIG / "resolution_summary.tsv")}
    sp, ge, ab = sm["species"], sm["genus"], sm["above genus"]
    n = int(sp["n"])
    tier = collections.Counter(r["tier"] for r in rd(EXTRA))
    n_pred = sum(tier.values())

    # THE ARTEFACT CASE IS READ OFF THE TWO CALL TABLES, not named from memory. It is the
    # taxon labelled a pathogen of another plant that loses the most runs between the
    # arms, which is what "db2 removes a false call" means in one organism.
    det = {a: rd(p) for a, p in DET.items()}
    calls = {a: sum(1 for r in det[a] if r["taxon_class"] != "host") for a in det}
    runs_of = {a: collections.Counter(r["taxon"] for r in det[a]) for a in det}
    klass = {r["taxon"]: r["taxon_class"] for a in det for r in det[a]}
    lost = collections.Counter({t: runs_of["db1p"][t] - runs_of["db2"][t]
                                for t in set(runs_of["db1p"]) | set(runs_of["db2"])
                                if klass[t] == "plant_pathogen"})
    case, drop = lost.most_common(1)[0]
    by_class = {k: (sum(1 for r in det["db1p"] if r["taxon_class"] == k),
                    sum(1 for r in det["db2"] if r["taxon_class"] == k))
                for k in ("resident", "wheat_pathogen", "plant_pathogen")}

    def line(s):
        return (f"{s['bucket']}: median {float(s['median_db1p']):.2%} to "
                f"{float(s['median_db2']):.2%}, a change of "
                f"{float(s['median_delta_pp']):+.3f} points in the median run, share up "
                f"in {int(s['n_up']):,} runs and down in {int(s['n_down']):,}, "
                f"{int(s['total_delta_reads']):+,d} reads across the cohort")

    text = para(
        "The Purpose Test: What the Predicted References Did",
        "Caption for resolution_reads.png (a) and resolution.png (b). SUPPLEMENTARY.",
        "",
        "GENERATED by caption.py — do not hand-edit, the numbers will drift.",
        "",
        "",
        "FULL CAPTION",
        "",
        f"db2 is db1p plus {n_pred} gene-predicted genomes and nothing else, so every "
        f"difference between the arms is attributable to those references. (a) is the "
        f"result in three numbers: the net FUNGAL READS that come to rest at each rank in "
        f"db2 against db1p, summed over {n:,} runs, with the number of runs moving that "
        f"way under each bar. (b) is the evidence that those totals are not a handful of "
        f"deep libraries: one curve per rank, the cumulative distribution over the same "
        f"runs of each run's change in the SHARE of its fungal reads resting there. A "
        f"curve lying wholly to one side of the dotted zero line means the direction held "
        f"in every run; where a curve crosses 0.5 is the median run.",
        "",
        f"THE READS MOVE UP, not down, and that is the predictions working rather than "
        f"failing. " + line(sp) + ". " + line(ge) + ". " + line(ab) + ".",
        "",
        f"THE TWO PANELS COUNT DIFFERENT THINGS and their run counts therefore differ: (a) "
        f"counts reads, (b) counts each rank's share of a run's fungal reads, and a run can "
        f"gain reads at a rank while that rank's share of its reads falls. Genus gains "
        f"reads in {int(ge['n_up_reads']):,} of {n:,} runs and gains share in "
        f"{int(ge['n_up']):,}.",
        "",
        f"The worklist is three tiers and they predict different directions, which is why "
        f"the pooled movement has to be read against what was built: tier A is "
        f"{tier['A']} genomes already in the reference scope with no gene model, present "
        f"in the database and uncallable, so giving them CDS puts a COMPETITOR in a genus "
        f"the database already holds; tier C2 is {tier['C2']} deliberate competitors for a "
        f"callable taxon that had none, whose intended effect is reads moving UP to the "
        f"genus node so that Kraken2's LCA can decline to name a species; and tier B is "
        f"{tier['B']} genomes in a genus the database did not hold at all, which is the "
        f"only tier the question 'do reads move DOWN to species' is about. "
        f"{tier['A'] + tier['C2']} of the {n_pred} therefore predict exactly the movement "
        f"the figure shows.",
        "",
        f"So the result is ARTEFACT REMOVAL rather than resolution gain. Calls fall from "
        f"{calls['db1p']:,} to {calls['db2']:,} across the cohort, the host aside: "
        + ", ".join(f"{k.replace('_', ' ')}s {v[0]:,} to {v[1]:,}"
                    for k, v in by_class.items())
        + f". The clearest single case is {case}, a pathogen of another plant, called in "
        f"{runs_of['db1p'][case]} runs under db1p and in {runs_of['db2'][case]} under db2: "
        f"its reads were Pleosporaceae reads with nowhere better to go, and with "
        f"Alternaria triticina in the database they go there instead. The "
        f"predicted taxa are competitors only and can never themselves be a call, in "
        f"either arm, so a detection can never rest on our own gene prediction.",
        "",
        f"THE X AXIS IS SYMMETRIC-LOG. Changes span three orders of magnitude in both "
        f"directions and include exact zero, so the axis is linear within {LIN} of a "
        f"percentage point of zero and logarithmic outside it. That is why the curves "
        f"stand up steeply near the middle: most runs change by a few hundredths of a "
        f"point, and the handful that change by tens of points are the tails.",
        "",
        f"Fungal reads only. The host is most of a plant RNA-seq library and resolves at "
        f"species, so it sets the all-reads denominator and buries any fungal movement "
        f"below the second decimal place; the restriction is a lineage test on the Fungi "
        f"node, not a name match. All {n:,} runs classified in both arms are drawn, rather "
        f"than the field-wheat set the other panels narrow to, because the question here "
        f"is about the database and every run is evidence about it.",
        "",
        "",
        "SHORT CAPTION",
        "",
        f"What the {n_pred} gene-predicted genomes did, db2 being db1p plus those "
        f"references and nothing else. (a) Net fungal reads coming to rest at each "
        f"taxonomic rank in db2 against db1p, summed over the {n:,} runs classified in "
        f"both arms, with the number of runs moving that way under each bar. (b) One curve "
        f"per rank: the cumulative distribution over the same runs of each run's change in "
        f"the SHARE of its fungal reads resting there, on a symmetric-log axis that is "
        f"linear within {LIN} of a percentage point of zero. The reads move UP rather than "
        f"down, which is the predictions working: species "
        f"{int(sp['total_delta_reads']):+,d} reads and "
        f"{float(sp['median_delta_pp']):+.3f} points in the median run, genus "
        f"{int(ge['total_delta_reads']):+,d} and {float(ge['median_delta_pp']):+.3f}, "
        f"above genus {int(ab['total_delta_reads']):+,d} and "
        f"{float(ab['median_delta_pp']):+.3f}. {tier['A'] + tier['C2']} of the {n_pred} "
        f"are competitors in a genus the database already held, so they predict exactly "
        f"that movement, and the result is artefact removal rather than resolution gain: "
        f"calls fall from {calls['db1p']:,} to {calls['db2']:,}, pathogens of another "
        f"plant from {by_class['plant_pathogen'][0]} to {by_class['plant_pathogen'][1]}, "
        f"and {case} from {runs_of['db1p'][case]} runs to {runs_of['db2'][case]}. Fungal "
        f"reads only; a predicted taxon is a competitor in the index and can never itself "
        f"be a call.",
    )
    write(FIG / "resolution_caption.txt", text)


if __name__ == "__main__":
    main()
