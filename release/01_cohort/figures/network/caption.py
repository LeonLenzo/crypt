RELATIONS = MODULE / "data" / "curation" / "relations.tsv"


def read(path):
    with open(path, newline="", encoding="utf-8") as fh:
        return list(csv.DictReader(fh, delimiter="\t"))


def network_caption(data):
    green = sum(1 for c in data.cohort if net.field_wheat(c))
    hollow = [b for b in data.projects if b not in data.used]
    hollow_runs = sum(1 for c in data.cohort if c["BioProject"] in hollow)
    grey = len(data.papers) - len(data.depositing)
    shared = [b for b in data.projects
              if len({e[0] for e in data.edges if e[1] == b}) > 1]
    drawn_reanalysis = len(data.reanalysis_edges)
    mentions = len(data.mentioned)
    per_paper = collections.Counter(e[0] for e in data.edges)
    multi = {d: n for d, n in per_paper.items() if n > 1}

    return reflow(f"""The Cohort as a Network
Caption for network.png, key in network_legend.png

GENERATED by figures/network/caption.py — do not hand-edit, the numbers will drift.


FULL CAPTION

How the cohort was assembled, read outward: one search, the papers it found, the
deposits those papers made, and the runs inside them. {len(data.papers)} papers,
{len(data.projects)} BioProjects and {len(data.cohort):,} runs.

The diamond at the centre is the search. It is not a datum; it is there because
without it the graph is a dozen unconnected components that a layout drives to the
rim, and because every paper's claim to be in this figure runs through it.

Filled circles are the {len(data.depositing)} papers whose reads are in the cohort.
Hollow circles are {grey} papers that passed full-text screening, report sequencing of
field material, and deposited nothing this cohort could use — mostly virome surveys
reporting consensus genomes rather than reads. A paper that deposited nothing AND ran
no field sequencing is a different kind of study and is absent entirely.

THE HOLLOW RING IS A RESULT, NOT A MARGIN. Of the papers that got this far, almost as
many deposited nothing usable as deposited something.

Blue circles are BioProjects, each surrounded by its runs: green where the run is
field-collected Triticum, hollow where it is lab material, off-host, or not RNA-seq.
network_declared.png redraws this ring by what each study declared.
{green:,} of {len(data.cohort):,} runs are field wheat.

{len(hollow)} BioProjects are drawn hollow, with no sample cloud at all
({hollow_runs} runs). They hold no field wheat — barley, lab material — and their runs
are still counted everywhere else; drawing their clouds spent a quarter of the canvas
on samples the analysis does not use.

EDGES ARE PRIMARY ATTRIBUTION ONLY. An edge means this paper generated this deposit.
There are {len(data.edges)}, and every BioProject has at most one
except {', '.join(shared) if shared else 'none'}.
{f"{len(multi)} papers deposit more than once." if len(multi) > 1 else
  f"One paper deposits more than once." if multi else
  "No paper deposits more than once."}
The figure is therefore close to a forest, which is the point: it is what the cohort
looks like once reuse is separated from generation.

Reanalysis edges are NOT drawn. {drawn_reanalysis} curated reanalyses exist and the
solver can draw them dashed (solve_network.py --reanalysis), but that is a check on the
layout rather than a page figure: it uses its own palette and its own solved positions,
not these. A further {mentions} paper-to-deposit links are mentions in a text nobody has
adjudicated, and are drawn nowhere.


WHAT IS NOT SHOWN

The {mentions} unadjudicated mentions above. "Named in a paper's text but not in its
deposit section" is not evidence of reanalysis: it is satisfied by a citation in a
discussion. Inferring reanalysis from it labelled 17 edges where 6 had ever been
decided, so only curated relations are drawn.

Node positions carry no meaning. They are read from network_nodes.tsv, a hand-editable
table seeded from the solver and then adjusted, so a node sits where it was placed:
broadly, angle is its paper's bearing and radius is the shortest the solver could reach
without an edge crossing another deposit's samples, but neither encodes a quantity and
several nodes were moved for legibility. Cloud area does track run count, through the
packing, but it is not calibrated and should not be read off.


SHORT CAPTION

The cohort as a network: {len(data.papers)} papers, {len(data.projects)} BioProjects,
{len(data.cohort):,} runs. The centre is the search; orange papers deposited reads the
cohort uses, hollow papers are field surveys that deposited nothing usable. Each
BioProject carries its runs, green for field-collected Triticum
({green:,} of {len(data.cohort):,}) and hollow otherwise. Edges show primary
attribution only, {len(data.edges)} of them; the {drawn_reanalysis} curated reanalyses
are not drawn.


SOURCES

  figure   release/01_cohort/figures/network/plot_network.py, from network_nodes.tsv
  solver   release/01_cohort/figures/network/solve_network.py (writes network_nodes.tsv)
  layout   network_layout.json (the solver's cache; --layout to recompute)
  caption  release/01_cohort/figures/network/caption.py
  data     data/outputs/supp_data_s1_studies.tsv, supp_data_s2_cohort.tsv
  relation data/curation/relations.tsv  (who generated what, and the evidence)
""")



LAB_MATERIAL = MODULE / "data" / "curation" / "lab_material.tsv"


def reflow(text, width=86):
    """Wrap the prose paragraphs and leave the indented blocks alone.

    The template is written at a fixed width and every number interpolated into it
    changes the line lengths, so what is written out is ragged unless it is rewrapped
    after the substitution rather than before.
    """
    out = []
    for i, block in enumerate(text.split("\n\n")):
        # Block 0 is the title and its figure line, which are two lines on purpose.
        # An indented block is a table. Everything else is prose and gets rewrapped.
        if i == 0 or block.startswith("  ") or len(block) < width:
            out.append(block)
            continue
        out.append(textwrap.fill(" ".join(block.split()), width=width))
    return "\n\n".join(out)


def plural(n, one, many=None):
    return f"{n} {one if n == 1 else (many or one + 's')}"


def listed(items):
    """a, b and c."""
    return (" and ".join(items) if len(items) < 3
            else ", ".join(items[:-1]) + " and " + items[-1])


def lab_materials():
    """material -> the lab-only deposits holding it, so the caption names what is there."""
    rows = [l for l in LAB_MATERIAL.read_text(encoding="utf-8").splitlines()
            if l and not l.startswith("#")]
    out = collections.defaultdict(set)
    for row in csv.DictReader(rows, delimiter="\t"):
        out[row["material"].replace("_", " ")].add(row["BioProject"])
    return out


def declared_caption(data):
    named = plot.declarations()
    kind = plot.project_settings(data)
    runs = collections.Counter(c["BioProject"] for c in data.cohort)
    by_declaration = collections.Counter()
    runs_by_declaration = collections.Counter()
    for b in data.projects:
        key = "; ".join(named.get(b, [])) or plot.UNDECLARED_LABEL
        by_declaration[key] += 1
        runs_by_declaration[key] += runs[b]
    top, top_n = by_declaration.most_common(1)[0]
    lab = [b for b in data.projects if kind[b] == "lab"]
    settings = collections.defaultdict(set)
    for c in data.cohort:
        settings[c["BioProject"]].add(c["setting"])
    mixed = sum(1 for b in data.projects if len(settings[b]) > 1)
    lab_all = sum(1 for c in data.cohort if c["setting"] == "lab")
    lab_drawn = sum(1 for c in data.cohort
                    if c["setting"] == "lab" and c["BioProject"] in data.used)
    lab_hidden = lab_all - lab_drawn
    hollow = [b for b in data.projects if b not in data.used]
    field_hollow = [b for b in hollow if kind[b] == "field"]
    omitted = len(data.papers) - len(data.depositing)
    green = sum(1 for c in data.cohort if net.field_wheat(c))
    drawn = sum(len(v) for v in data.members.values())
    materials = sorted(m for m, bs in lab_materials().items()
                       if bs & set(lab))
    roll = "\n".join(
        f"  {n:>2} {'deposit,' if n == 1 else 'deposits,':<9}"
        f"{runs_by_declaration[k]:>6,} runs   {k}"
        for k, n in by_declaration.most_common())

    return reflow(f"""What Each Deposit Said It Was Looking For
Caption for network_declared.png, key in network_declared_legend.png

GENERATED by figures/network/caption.py --declared — do not hand-edit, the numbers
will drift.


FULL CAPTION

The cohort redrawn so the outer ring carries the study's own declaration:
{len(data.depositing)} papers, {len(data.projects)} BioProjects and {len(data.cohort):,}
runs, at the positions network.png uses. Nothing has moved between the two figures.

Each BioProject is filled by the pathogen the generating paper named, shaped by whether
the deposit holds any field material (circle) or is lab only (square), and outlined
heavily where it holds field wheat. Its runs surround it: green for field-collected
Triticum, dark for lab material, hollow for field material off-host or not RNA-seq.

FIELD AND LAB ARE MARKED AT BOTH LEVELS, because neither level can carry it alone.
{mixed} deposits hold both kinds, so a square on them would be false and a circle alone
says nothing about the lab runs inside; a circle means the deposit HOLDS field material,
never that all of it is field. But {lab_drawn} of the {lab_all} lab runs in the cohort
sit inside a drawn cloud and the other {lab_hidden} are in the {len(lab)} lab-only
deposits, whose clouds are not drawn, so the run mark alone would show a fifth of the
lab arm and silently drop the rest.

{roll}

THE DECLARATION IS WHAT THE STUDY SAID, NOT WHAT IS IN THE READS. It is curated once
per BioProject from the paper that generated it, against a quoted sentence
(data/curation/declared_pathogens.tsv). It is not a detection and the two must not be
read as the same thing: the chapter's question is precisely what the reads hold that
the declaration does not.

{top_n} of {len(data.projects)} deposits declare {top}. That is the cohort, not a
sampling choice: public wheat RNA-seq is overwhelmingly a yellow-rust archive, and it
is why a pooled rate over these runs is a statement about surveillance effort.

The {plural(by_declaration[plot.UNDECLARED_LABEL], 'deposit')} that declare no
fungus are virome surveys. They are the only part of the cohort that did not condition on fungal disease,
so they are drawn as their own colour rather than as a missing value.

{plural(len(lab), 'deposit')} are lab only ({', '.join(lab)}), holding
{listed(materials)}. {plural(len(hollow), 'deposit')} carry no sample cloud because
they hold no field wheat, and {len(field_hollow)} of those are field surveys of another
host: a distinction the plain figure cannot draw, because there both are a hollow
circle.

{green:,} of {len(data.cohort):,} runs are field wheat; {drawn:,} runs are drawn inside a cloud.


WHAT IS NOT SHOWN

The {plural(omitted, 'paper')} that passed full-text screening, report field sequencing and
deposited nothing usable. They are a real attrition and they are drawn in network.png,
which is the figure for that question. Here they would be {omitted} unexplained nodes with no
deposit to colour.

Reanalysis edges, as in network.png. Edges are primary attribution only:
{len(data.edges)} of them, one paper to one deposit it generated.

Node positions carry no meaning. Cloud area tracks run count through the packing but is
not calibrated and should not be read off.


SHORT CAPTION

The cohort coloured by declaration: {len(data.depositing)} papers,
{len(data.projects)} BioProjects, {len(data.cohort):,} runs, at the positions of
network.png. Each BioProject is filled by the pathogen its generating paper named,
square where the deposit is lab only, and surrounded by its runs (green for field
wheat). {top_n} of {len(data.projects)} deposits name {top}. The fill is a declaration,
not a detection.


SOURCES

  figure   release/01_cohort/figures/network/plot_network.py --declared
  positions network_nodes.tsv (shared with network.png, unchanged)
  caption  release/01_cohort/figures/network/caption.py --declared
  data     data/outputs/supp_data_s1_studies.tsv, supp_data_s2_cohort.tsv
  declared data/curation/declared_pathogens.tsv  (per BioProject, with the quote)
  material data/curation/lab_material.tsv
""")


def main(declared=False):
    data = net.Cohort()
    name = "network_declared_caption.txt" if declared else "network_caption.txt"
    text = declared_caption(data) if declared else network_caption(data)
    (FIG / name).write_text(text, encoding="utf-8")
    print(f"wrote {FIG / name}")


if __name__ == "__main__":
    ap = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    ap.add_argument("--declared", action="store_true",
                    help="the caption for network_declared.png instead")
    main(**vars(ap.parse_args()))
