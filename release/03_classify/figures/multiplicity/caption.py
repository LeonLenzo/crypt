#!/usr/bin/env python3
"""caption.py — the caption for the per-project multiplicity panel, written from the data.

    python release/03_classify/figures/multiplicity/caption.py

Reads  multiplicity_bars.tsv, multiplicity_projects.tsv, multiplicity_ramp.tsv
       ../../data/outputs/supp_data_s5_detections.tsv   the taxa behind the counts
Writes multiplicity_caption.txt

Every number is read at write time from the tables the panel was drawn from. See
crypt-figure-caption-discipline: a number a reader cannot recompute is one nobody can check.
"""

import collections
import csv
import sys
from pathlib import Path

HERE = Path(__file__).resolve().parents[2]              # release/03_classify
FIG = Path(__file__).resolve().parent
sys.path.insert(0, str(HERE.parent / "02_reference/scripts"))
from _caption import rd, para, write                    # noqa: E402
sys.path.insert(0, str(FIG))
# the analysed set comes from the prep script, not a second filter written here: the
# caption's taxon counts have to be over the runs the panel drew
from prep_multiplicity import analysed                  # noqa: E402

S5 = HERE / "data/outputs/supp_data_s5_detections.tsv"
ARM = "db2"
MIN_N = 10


def spearman(xs, ys):
    """Rank correlation, written out rather than imported: scipy is not a dependency here."""
    def rank(v):
        order = sorted(range(len(v)), key=lambda i: v[i])
        out = [0.0] * len(v)
        i = 0
        while i < len(order):           # ties take the mean rank, as they must
            j = i
            while j + 1 < len(order) and v[order[j + 1]] == v[order[i]]:
                j += 1
            for k in range(i, j + 1):
                out[order[k]] = (i + j) / 2
            i = j + 1
        return out
    rx, ry = rank(xs), rank(ys)
    n = len(xs)
    mx, my = sum(rx) / n, sum(ry) / n
    cov = sum((a - mx) * (b - my) for a, b in zip(rx, ry))
    sx = sum((a - mx) ** 2 for a in rx) ** 0.5
    sy = sum((b - my) ** 2 for b in ry) ** 0.5
    return cov / (sx * sy) if sx and sy else float("nan")


def main():
    bars = rd(FIG / "multiplicity_bars.tsv")
    proj = rd(FIG / "multiplicity_projects.tsv")
    ramp = rd(FIG / "multiplicity_ramp.tsv")

    n_runs = sum(int(r["n"]) for r in proj)
    bins = [r for r in ramp if r["k"] != "virus"]
    top = bins[-1]["klabel"]
    dist = {r["klabel"]: int(r["n_runs"]) for r in bins}
    ge2 = sum(n for k, n in dist.items() if k not in ("0", "1"))
    big = [r for r in proj if int(r["n"]) >= MIN_N]
    rates = sorted(float(r["rate"]) for r in big)
    worst = max(int(r["max"]) for r in proj)

    virus = [r for r in proj if r["virus"] == "1"]
    zero = [r for r in proj if float(r["rate"]) == 0]
    zero_v = [r for r in zero if r["virus"] == "1"]

    rho = spearman([float(r["rate"]) for r in proj], [float(r["log_f"]) for r in proj])
    deep_zero = sorted((float(r["log_f"]), r["project"]) for r in zero)
    med_all = sorted(float(r["log_f"]) for r in proj)[len(proj) // 2]
    deep = [p for lf, p in deep_zero if lf >= med_all]

    drawn = set(analysed())
    taxa = collections.Counter(
        r["taxon"] for r in rd(S5)
        if r["arm"] == ARM and r["taxon_class"] == "wheat_pathogen" and r["run"] in drawn)

    text = para(
        "Co-infection Multiplicity, by BioProject",
        "Caption for multiplicity.png.",
        "",
        "GENERATED by caption.py — do not hand-edit, the numbers will drift.",
        "",
        "",
        "FULL CAPTION",
        "",
        f"How many wheat pathogens one run carries, summarised per study. Each bar is one "
        f"BioProject and its length is its analysed runs divided into the share "
        f"carrying no wheat pathogen, one, two, three, and {top}; the darker the right-hand "
        f"end of a bar, the more of that study's samples held more than one pathogen at "
        f"once. The same {n_runs:,} field-collected Triticum aestivum runs as the panel "
        f"above, over {len(proj)} BioProjects, ordered by the share of runs carrying two or "
        f"more. The number at the right of each row is that project's analysed runs, and "
        f"the {len(proj) - len(big)} projects with fewer than {MIN_N} sit in a block of "
        f"their own at the foot of the panel, because a rate over four or eight runs is "
        f"not a rate.",
        "",
        f"Across the cohort "
        + ", ".join(f"{dist[b['klabel']]:,} runs ({dist[b['klabel']] / n_runs:.1%}) carry "
                    f"{b['klabel']}" for b in bins)
        + f", so {ge2:,} runs ({ge2 / n_runs:.1%}) carry two or more and the most crowded "
        f"run holds {worst}. THE POOLED FIGURE IS NOT THE FINDING: across the {len(big)} "
        f"projects with at least {MIN_N} runs the rate runs from {rates[0]:.1%} to "
        f"{rates[-1]:.1%}, and the spread between studies is larger than anything a single "
        f"number over the cohort could report. {len(taxa)} wheat pathogens contribute "
        f"{sum(taxa.values()):,} calls, led by "
        + ", ".join(f"{t} ({n:,})" for t, n in taxa.most_common(3)) + ".",
        "",
        f"THE PROJECT IS THE UNIT HERE, and in the panel above it is the run. That is "
        f"deliberate: what varies between studies is what they sampled and where, so each "
        f"project is one observation of its own rate and the panel draws the spread rather "
        f"than averaging it away. A pairwise co-occurrence view of the same calls is NOT "
        f"drawn, having been measured and rejected: conditioning on BioProject reverses "
        f"three of the eight commonest pathogen pairs, Puccinia striiformis with P. "
        f"triticina going from a marginal odds ratio of 0.28 to 4.43 within projects, so "
        f"an association drawn over runs would report where the surveys sampled.",
        "",
        f"THE SECOND COLUMN IS THE OBVIOUS OBJECTION, TESTED. A study with few "
        f"co-infections might simply have shallow libraries, so each point is that "
        f"project's median fungal reads per run, the depth that remains once the host is "
        f"removed, on a log axis spanning three orders of magnitude. The rank correlation "
        f"with the co-infection rate is {rho:+.2f} over {len(proj)} projects, and "
        f"{len(deep)} of the {len(zero)} projects with no co-infection at all sit at or "
        f"above the cohort's median depth ({', '.join(deep)}). Depth is therefore not what "
        f"separates the top of the panel from the bottom.",
        "",
        f"ACCESSIONS IN GREY are virus surveys, which declared no fungus because they were "
        f"not looking for one; {len(zero_v)} of the {len(zero)} projects with no "
        f"co-infection are among them, and {len(virus)} of the {len(proj)} projects in "
        f"total. The marker is read from the curated study_target column of "
        f"supp_data_s2_cohort.tsv, never inferred from a study having declared nothing.",
        "",
        f"Counting follows supp_data_s6_runs.tsv, one row per run, and counts every wheat "
        f"pathogen called in the arm: {len(taxa)} taxa, where the panel above draws 13 rows "
        f"because Alternaria alternata is shown inside the Alternaria genus row. That "
        f"difference moves exactly one run from three pathogens to two and no run across "
        f"the two-or-more boundary. A call is presence, not infection; release/04_align "
        f"confirms each one read by read.",
        "",
        "",
        "SHORT CAPTION",
        "",
        f"How many wheat pathogens one run carries, summarised per study over the "
        f"{n_runs:,} field-collected Triticum aestivum runs of {len(proj)} BioProjects. "
        f"Each bar is one project's analysed runs divided into the share carrying no wheat "
        f"pathogen, one, two, three and {top}, ordered by the share carrying two or more; "
        f"the count at the right of a row is that project's analysed runs, and the "
        f"{len(proj) - len(big)} projects with fewer than {MIN_N} runs sit in a block of "
        f"their own at the foot of the panel. Pooled, {ge2:,} runs ({ge2 / n_runs:.1%}) "
        f"carry two or more and the most crowded holds {worst}, but across the {len(big)} "
        f"projects with at least {MIN_N} runs the rate spans {rates[0]:.1%} to "
        f"{rates[-1]:.1%}, which is the finding rather than the pooled figure. The second "
        f"column is each project's median fungal reads per run on a log axis, the depth "
        f"remaining once the host is removed: its rank correlation with the co-infection "
        f"rate is {rho:+.2f}, so depth does not separate the top of the panel from the "
        f"bottom. Accessions in grey are virus surveys ({len(virus)} of {len(proj)}), "
        f"which declared no fungus because they were not looking for one. "
        f"{len(taxa)} wheat pathogens contribute {sum(taxa.values()):,} calls; counting "
        f"follows supp_data_s6_runs.tsv and a call is presence, not infection.",
    )
    write(FIG / "multiplicity_caption.txt", text)


if __name__ == "__main__":
    main()
