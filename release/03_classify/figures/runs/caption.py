#!/usr/bin/env python3
"""caption.py — the caption for the four detection-space panels, written from the data.

    python release/03_classify/figures/runs/caption.py

Reads  runs_points.tsv, runs_floors.tsv     (beside this script, from prep_runs.py)
       ../../data/inputs/panel_runs.tsv     the ladder and what each rung was to show
       ../../../01_cohort/data/curation/lab_material.tsv   what each library was made from
Writes runs_caption.txt

One caption for all four panels, because they are one figure: the same axes, the same
floors, the same colours, read left to right as a ladder. Every number is read at write
time from what the panels were drawn from.
"""

import csv
import sys
from pathlib import Path

HERE = Path(__file__).resolve().parents[2]              # release/03_classify
FIG = Path(__file__).resolve().parent
sys.path.insert(0, str(HERE.parent / "02_reference/scripts"))
from _caption import rd, para, write                    # noqa: E402

PANEL = HERE / "data/inputs/panel_runs.tsv"
MATERIAL = HERE.parent / "01_cohort/data/curation/lab_material.tsv"


def rdc(path):
    """Read a TSV whose header is preceded by comments; _caption.rd does not skip them."""
    with open(path) as fh:
        return list(csv.DictReader((l for l in fh if not l.startswith("#")),
                                   delimiter="\t"))


def main():
    pts = rd(FIG / "runs_points.tsv")
    fl = {r["item"]: r["value"] for r in rd(FIG / "runs_floors.tsv")}
    pan = rdc(PANEL)
    mat = {r["run"]: r["material"] for r in rdc(MATERIAL)}

    by = {}
    for r in pts:
        by.setdefault(r["run"], []).append(r)
    rung = {r["rung"]: r for r in pan}

    def line(k):
        p = rung[k]
        rows = by[p["run"]]
        called = [x for x in rows if x["call"] == "detected"]
        return (p, rows, called,
                ", ".join(sorted(x["taxon"] for x in called)) or "nothing")

    bits = []
    for k in sorted(rung):
        p, rows, called, names = line(k)
        bits.append(f"  {k}. {p['label']} ({p['run']}, "
                    f"{mat.get(p['run'], 'field-collected')}): {len(rows):,} candidates, "
                    f"{len(called)} called \\u2014 {names}")
    ladder = "\n".join(bits)

    cf, sf = float(fl["coverage_floor"]), float(fl["saturation_floor"])
    n_pts = len(pts)
    n_called = sum(1 for r in pts if r["call"] == "detected")

    text = para(
        "Four Runs, Opened Up on the Axes the Call Is Made On",
        "Caption for runs_1 to runs_4.png.",
        "",
        "GENERATED by caption.py — do not hand-edit, the numbers will drift.",
        "",
        "",
        "FULL CAPTION",
        "",
        f"Four of the columns in the panel above, drawn in full. Each point is one taxon "
        f"Kraken2 assigned reads to in that run, placed by the two quantities the call is "
        f"made on: redundancy available on the x axis, the reads the library could have "
        f"spent on that taxon, and coverage observed on the y, the share of its k-mer space "
        f"actually seen. Both are divided by the taxon's OWN minimizer total in db2, which "
        f"is what makes the null one curve for every taxon rather than one per taxon. Axes "
        f"are log scales labelled as the exponent. Filled points are calls, hollow points "
        f"are not; {n_called} of {n_pts:,} candidates across the four runs are called.",
        "",
        f"Three lines, and together they are the whole decision. The solid curve is the "
        f"null, the coverage that reads spread uniformly would give at that depth. The "
        f"dotted line is the coverage floor at {cf:.0%}, anchored on the off-host null. The "
        f"dashed curve is the abundance floor, {sf:.2f} of the null, which bends down at "
        f"low depth because a shallow library could not have reached {sf:.0%} whatever was "
        f"present. The two cross at redundancy 0.51: above it the dashed curve binds, below "
        f"it the dotted line does, and no point is ever judged by both.",
        "",
        f"The four runs are a ladder through the control set, and each was chosen with its "
        f"expectation written down first, in data/inputs/panel_runs.tsv, so the panels are "
        f"a test rather than an illustration:",
        "",
        ladder,
        "",
        f"Read left to right they say what a column of the panel above can contain. A spore "
        f"library has one organism in it and the method finds one. A glasshouse plant is "
        f"not sterile, and the Cladosporium in the second panel is the method behaving "
        f"correctly rather than failing. A field sample carries a crowd. And an "
        f"uninoculated plant carries no fungus at all, which is the only panel where the "
        f"right answer is nothing and the floors have to decline everything above the "
        f"rejected cloud \\u2014 the host is still called there, because the host is ranked "
        f"and not thresholded.",
        "",
        f"The rejected cloud is most of each panel and is deliberately unlabelled. It has "
        f"no identity worth reading: what it shows is that the floors refuse far more than "
        f"they admit, and that the refusals lie along the null rather than scattered, which "
        f"is what cross-mapping from a large reference looks like.",
    )
    write(FIG / "runs_caption.txt", text)


if __name__ == "__main__":
    main()
