#!/usr/bin/env python3
"""caption.py — write the captions for the cohort figures from the tables themselves.

    python release/01_cohort/scripts/caption.py

Reads  data/outputs/supp_data_s1_studies.tsv, supp_data_s2_cohort.tsv
       data/curation/relations.tsv
       figures/cohort_map_points.tsv, cohort_map_summary.tsv
Writes figures/cohort_network_caption.txt
       figures/cohort_map_caption.txt

Nothing below is prose with numbers typed into it. The narrative is a template and every
figure in it is read at write time, for the reason the crop-map caption records: a
caption hand-patched across a session drifts, and a claim nobody can recompute is one
nobody can check. The panel A numbers come from plot_cohort_network's own Cohort class
rather than being counted again here, so the caption cannot disagree with the figure.
"""

import collections
import csv
import sys
from pathlib import Path

HERE = Path(__file__).resolve().parent
sys.path.insert(0, str(HERE))
import plot_cohort_network as net

MODULE = HERE.parent
FIGDIR = MODULE / "figures"
RELATIONS = MODULE / "data" / "curation" / "relations.tsv"


def read(path):
    with open(path, newline="", encoding="utf-8") as fh:
        return list(csv.DictReader(fh, delimiter="\t"))


def summary_values():
    return {r["measure"]: int(r["value"])
            for r in read(FIGDIR / "cohort_map_summary.tsv")}


def network_caption(data):
    green = sum(1 for c in data.cohort if net.field_wheat(c))
    hollow = [b for b in data.projects if b not in data.used]
    hollow_runs = sum(1 for c in data.cohort if c["BioProject"] in hollow)
    grey = len(data.papers) - len(data.depositing)
    shared = [b for b in data.projects
              if len({e[0] for e in data.edges if e[1] == b}) > 1]
    drawn_reanalysis = len(data.reanalysis_edges)
    mentions = len(data.mentioned)
    per_paper = collections.Counter(e[0] for e in data.edges)
    multi = {d: n for d, n in per_paper.items() if n > 1}

    return f"""The Cohort as a Network
Caption for figures/cohort_network.{{png,pdf}}, key in cohort_network_legend.png

GENERATED by scripts/caption.py — do not hand-edit, the numbers will drift.


FULL CAPTION

How the cohort was assembled, read outward: one search, the papers it found, the
deposits those papers made, and the runs inside them. {len(data.papers)} papers,
{len(data.projects)} BioProjects and {len(data.cohort):,} runs.

The diamond at the centre is the search. It is not a datum; it is there because
without it the graph is a dozen unconnected components that a layout drives to the
rim, and because every paper's claim to be in this figure runs through it.

Orange circles are the {len(data.depositing)} papers whose reads are in the cohort.
Grey circles are {grey} papers that passed full-text screening, report sequencing of
field material, and deposited nothing this cohort could use — mostly virome surveys
reporting consensus genomes rather than reads. A paper that deposited nothing AND ran
no field sequencing is a different kind of study and is absent entirely.

THE GREY RING IS A RESULT, NOT A MARGIN. Of the papers that got this far, almost as
many deposited nothing usable as deposited something.

Blue circles are BioProjects, each surrounded by its runs: green where the run is
field-collected Triticum, hollow where it is lab material, off-host, or not RNA-seq.
{green:,} of {len(data.cohort):,} runs are field wheat.

{len(hollow)} BioProjects are drawn hollow, with no sample cloud at all
({hollow_runs} runs). They hold no field wheat — barley, lab material — and their runs
are still counted everywhere else; drawing their clouds spent a quarter of the canvas
on samples the analysis does not use.

EDGES ARE PRIMARY ATTRIBUTION ONLY. An edge means this paper generated this deposit.
There are {len(data.edges)}, and every BioProject has at most one
except {', '.join(shared) if shared else 'none'}.
{f"{len(multi)} papers deposit more than once." if len(multi) > 1 else
  f"One paper deposits more than once." if multi else
  "No paper deposits more than once."}
The figure is therefore close to a forest, which is the point: it is what the cohort
looks like once reuse is separated from generation.

Reanalysis edges are NOT drawn here. They are in the companion figure
cohort_network_reanalysis.png, dashed, where {drawn_reanalysis} curated reanalyses
appear. A further {mentions} paper-to-deposit links are mentions in a text that nobody
has adjudicated, and are drawn in neither figure.


WHAT IS NOT SHOWN

The {mentions} unadjudicated mentions above. "Named in a paper's text but not in its
deposit section" is not evidence of reanalysis: it is satisfied by a citation in a
discussion. Inferring reanalysis from it labelled 17 edges where 6 had ever been
decided, so only curated relations are drawn.

Node positions carry no meaning. Radius is the shortest the layout could place a
deposit at without its edge crossing another deposit's samples; angle is its paper's
bearing. Neither encodes a quantity. Cloud area does track run count, through the
packing, but it is not calibrated and should not be read off.


SHORT CAPTION

The cohort as a network: {len(data.papers)} papers, {len(data.projects)} BioProjects,
{len(data.cohort):,} runs. The centre is the search; orange papers deposited reads the
cohort uses, grey papers are field surveys that deposited nothing usable. Each
BioProject carries its runs, green for field-collected Triticum
({green:,} of {len(data.cohort):,}) and hollow otherwise. Edges show primary
attribution only, {len(data.edges)} of them; reanalysis is shown dashed in
cohort_network_reanalysis.png.


SOURCES

  figure   release/01_cohort/scripts/plot_cohort_network.py
  layout   figures/cohort_network_layout.json (cached; --layout to recompute)
  manual   scripts/plot_network_manual.py, from figures/cohort_network_nodes.tsv
  caption  release/01_cohort/scripts/caption.py
  data     data/outputs/supp_data_s1_studies.tsv, supp_data_s2_cohort.tsv
  relation data/curation/relations.tsv  (who generated what, and the evidence)
"""


def map_caption(data):
    s = summary_values()
    pts = read(FIGDIR / "cohort_map_points.tsv")
    loc = [p for p in pts if p["placement"] == "Locality"]
    ctry = sorted([p for p in pts if p["placement"] == "Country"],
                  key=lambda p: -int(p["runs"]))
    prec = {k.replace("locality runs at precision: ", ""): v
            for k, v in s.items() if k.startswith("locality runs at precision")}
    biggest = max(loc, key=lambda p: int(p["runs"]))
    top = ", ".join(f"{p['location']} {p['runs']}" for p in ctry[:3])

    return f"""Where the Cohort Was Collected
Caption for figures/cohort_map.{{png,pdf}}, key in cohort_map_legend.png

GENERATED by scripts/caption.py — do not hand-edit, the numbers will drift.


FULL CAPTION

Collection origin of the field wheat cohort: {s['field-wheat runs in cohort']:,} runs,
of which {s['drawn at a locality']:,} are drawn at a named place and
{s['drawn at a country centroid']} at a country centroid.

Only field-collected Triticum is plotted. Lab material and off-host runs are excluded
even where they carry coordinates, because an isolate deposit records where its pustule
was collected, not where anything was sampled. The test is the same one that colours a
run green in the network figure, so the two panels describe the same samples.

Green circles are {len(loc)} named places. Blue circles are {len(ctry)} country
centroids, carrying the runs whose papers record a country and nothing finer; the
largest are {top}.

A BLUE CIRCLE IS NOT A COLLECTION SITE. It states WHICH COUNTRY and sits at the
centroid of that country's largest landmass polygon, a place nobody sampled.

Point area scales with the LOGARITHM of the runs at that point, so a larger circle
means more runs but area is not proportional to count. Points are semi-transparent, so
overlapping places compound into darker patches. The largest named place is
{biggest['location']} with {biggest['runs']} runs; the key runs to 65 because the
largest marks on the map are blue, not green.

THE BIGGEST MARKS ARE THE LEAST PRECISE, which is the opposite of what a reader
expects. Country circles carry up to {max(int(p['runs']) for p in ctry)} runs and named
places at most {max(int(p['runs']) for p in loc)}.

The inset magnifies Europe, North Africa and the Near East, where
{sum(1 for p in pts if -19 <= float(p['lon']) <= 38 and 27 <= float(p['lat']) <= 58)}
of the {len(pts)} points sit. It is cropped to its contents rather than to the region,
and placed over its own ground extended west across the Atlantic. It hides no point it
does not itself redraw, larger.


WHAT IS NOT SHOWN

{s['not drawn: no usable place']} runs name no place at all and are absent from the
map while remaining in every count elsewhere.

The {s['drawn at a country centroid']} country-level runs are not a geocoding failure.
Each was pursued to the source: three supplementary tables were read end to end
(Lewis et al. 2024 Dataset S2, Hubbard et al. 2015, and Table S13 of the 2025 brown
rust study, joined run by run through ENA's secondary accessions), and each records a
country and nothing finer for exactly these samples. Where a finer value existed it was
taken — five Western Australian runs were placed at Kulin, Corrigin, Goomalling and
Wongan Hills from Table 1 of 10.3390/v15020401, matched on the BioSample isolate field.

Named places are placed at several precisions, recorded per run in
curated_attributes.tsv: {', '.join(f'{v} {k}' for k, v in prec.items())}.


SHORT CAPTION

Collection origin of {s['field-wheat runs in cohort']:,} field wheat runs. Green
circles are {s['drawn at a locality']:,} runs at {len(loc)} named places; blue circles
are {s['drawn at a country centroid']} runs at {len(ctry)} country centroids, drawn at
a place nobody sampled because their papers record no finer location. Point area scales
with log run count. {s['not drawn: no usable place']} runs name no place and are
absent. Inset magnifies Europe, North Africa and the Near East.


SOURCES

  figure   release/01_cohort/scripts/map_cohort.R
  prep     release/01_cohort/scripts/prep_cohort_map.py
  caption  release/01_cohort/scripts/caption.py
  data     figures/cohort_map_points.tsv, cohort_map_summary.tsv
  geocode  research/01_literature/retrieve/geocode_localities.py
  supps    data/raw/supplements/
"""


def main():
    data = net.Cohort()
    for name, text in (("cohort_network_caption.txt", network_caption(data)),
                       ("cohort_map_caption.txt", map_caption(data))):
        (FIGDIR / name).write_text(text, encoding="utf-8")
        print(f"wrote {FIGDIR / name}")


if __name__ == "__main__":
    main()
