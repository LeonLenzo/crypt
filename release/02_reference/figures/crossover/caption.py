#!/usr/bin/env python3
"""caption.py — the caption for the minimizer-crossover supplementary figure.

    python release/02_reference/figures/crossover/caption.py

Reads  crossover_matrix.tsv                              (beside this script)
       ../../data/outputs/supp_data_s3_reference.tsv      for the matrix category per taxon
       ../../data/curation/build_plan.tsv                 for the assembly count
Writes crossover_caption.txt

Every number is read from the matrix the panel is drawn from, so the caption cannot narrate a
different figure. Nothing is prose-with-numbers-typed-in: rerun after any change to the matrix.
"""

import sys
from pathlib import Path

HERE = Path(__file__).resolve().parent
ROOT = Path(__file__).resolve().parents[2]              # release/02_reference
sys.path.insert(0, str(ROOT / "scripts"))
from _caption import rd, para, write                     # noqa: E402

S3 = ROOT / "data/outputs/supp_data_s3_reference.tsv"
PLAN = ROOT / "data/curation/build_plan.tsv"
MATRIX = HERE / "crossover_matrix.tsv"
PROBLEM_THRESH = 0.20
K, L = 35, 31


def load_matrix():
    rows = [r for r in (ln.rstrip("\n").split("\t")
            for ln in MATRIX.open())]
    data = rows[1:]
    n = len(data)
    taxid = [r[0] for r in data]
    genus = [r[5] for r in data]
    family = [r[4] for r in data]
    name = [r[6] for r in data]
    dist = [int(r[7]) for r in data]
    M = [[int(x) for x in r[8:8 + n]] for r in data]
    return n, taxid, genus, family, name, dist, M


def main():
    n, taxid, genus, family, name, dist, M = load_matrix()

    cat = {r["ncbi_taxid"]: r["phibase_col"] for r in rd(S3)}
    cats = [cat.get(t, "none") for t in taxid]
    n_res = cats.count("none")
    n_plant = cats.count("plant_pathogen")
    n_wp = cats.count("wheat_pathogen")
    n_genera = len(set(genus))

    want = set(taxid)
    n_asm = sum(1 for r in rd(PLAN) if r["species_taxid"] in want)

    # crossover metric and the within/across-genus split
    same_sum = same_k = cross_sum = cross_k = 0.0
    biggest = (0.0, "", "")
    for i in range(n):
        for j in range(i + 1, n):
            mn = min(dist[i], dist[j])
            x = M[i][j] / mn if mn else 0.0
            if genus[i] == genus[j]:
                same_sum += x; same_k += 1
            else:
                cross_sum += x; cross_k += 1
            if M[i][j] > biggest[0]:
                biggest = (M[i][j], name[i], name[j])
    same_mean = same_sum / same_k if same_k else 0
    cross_mean = cross_sum / cross_k if cross_k else 0

    # per wheat pathogen: max crossover to any other taxon, and the partner
    wp_idx = [i for i in range(n) if cats[i] == "wheat_pathogen"]
    prob = []
    clean = []
    for i in wp_idx:
        best = (0.0, None)
        for j in range(n):
            if j == i:
                continue
            mn = min(dist[i], dist[j])
            x = M[i][j] / mn if mn else 0.0
            if x > best[0]:
                best = (x, j)
        if best[0] >= PROBLEM_THRESH:
            prob.append((i, best[0], best[1]))
        else:
            clean.append(i)
    prob.sort(key=lambda t: -t[1])

    prob_lines = "\n".join(
        f"  {name[i]:<30}{x:>6.2f}   {name[j]}" for i, x, j in prob)
    rusts = [name[i] for i in clean if genus[i] == "Puccinia"]

    big_v, big_a, big_b = biggest

    write(HERE / "crossover_caption.txt", para(
        "Minimizer Crossover Among Fungi Recorded on Wheat",
        "Caption for crossover.png (supplementary), keyed by crossover_legend.png.",
        "",
        "GENERATED by caption.py — do not hand-edit, the numbers will drift.",
        "",
        "",
        "FULL CAPTION",
        "",
        f"Pairwise minimizer sharing among the {n:,} fungal taxa the USDA Plant-Fungal "
        f"Database records on wheat (the wheat row of the reference), spanning {n_genera} "
        f"genera and built from {n_asm:,} genome assemblies. For each taxon the set of "
        f"canonical minimizers of its coding sequence was computed (length {L} over {K}-base "
        f"windows, the db1p scheme), unioned across its assemblies; a cell is the exact "
        f"intersection of two such sets. Colour is crossover, the shared count divided by the "
        f"smaller taxon's total, so a cell reads as the fraction of the smaller taxon's "
        f"minimizers the two share: 0 (white) means the classifier can tell them apart, 1 "
        f"means it cannot. The diagonal is masked.",
        "",
        f"Rows and columns are ordered and bracketed by the NCBI taxonomy (phylum to species) "
        f"drawn as a cladogram on the top and left; radius encodes rank, not divergence. The "
        f"strip on each axis colours every taxon by its panel-A type: {n_res} recorded on "
        f"wheat with no pathogenicity record (green), {n_plant} pathogens of other plants "
        f"(amber), and {n_wp} wheat pathogens (orange-red), using the matrix-figure palette.",
        "",
        f"Crossover is confined to the diagonal blocks. Mean crossover between congeners (same "
        f"genus) is {same_mean:.3f}; between taxa in different genera it is {cross_mean:.4f}, "
        f"effectively zero at this minimizer length. Sharing is therefore a within-genus "
        f"phenomenon: a read that cannot be resolved to species is nonetheless resolved to "
        f"genus, and no cross-genus taxon absorbs it.",
        "",
        "",
        "WHEAT PATHOGENS THAT ARE HARD TO RESOLVE",
        "",
        f"Each of the {n_wp} wheat pathogens is labelled on the right. The {len(prob)} whose "
        f"minimizers overlap another taxon's by at least {PROBLEM_THRESH:.0%} are highlighted "
        f"(bold red label, ringed diagonal cell): for these a species-level call is not fully "
        f"supported by sequence, and the taxon they are confused with is named below.",
        "",
        "  Wheat pathogen                 max.  confused with",
        prob_lines,
        "",
        f"The confusions are species complexes, not database errors: the bunt pair "
        f"(Tilletia), the Fusarium head-blight group, and the Alternaria, Pyricularia and "
        f"Ustilago complexes. The three wheat rusts resolve cleanly and are NOT highlighted "
        f"({', '.join(rusts)}), the separability that lets the classifier distinguish stripe, "
        f"leaf and stem rust despite their shared genus.",
        "",
        f"The largest single off-diagonal count is {big_v:,} minimizers, between {big_a} and "
        f"{big_b}.",
        "",
        "",
        "SHORT CAPTION",
        "",
        f"Pairwise minimizer sharing among the {n:,} fungal taxa the USDA Plant-Fungal "
        f"Database records on wheat, spanning {n_genera} genera and built from "
        f"{n_asm:,} genome assemblies. Each taxon's canonical coding-sequence minimizers "
        f"(length {L} over {K}-base windows, the db1p scheme) were unioned across its "
        f"assemblies; a cell is the exact intersection of two such sets, coloured as "
        f"crossover, the shared count over the smaller taxon's total, so 0 (white) means "
        f"the classifier can separate them and 1 that it cannot. The diagonal is masked. "
        f"Rows and columns are ordered by the NCBI taxonomy drawn as a cladogram on the "
        f"top and left, where radius is rank and not divergence, and the axis strips "
        f"colour each taxon by its panel-A type ({n_res} recorded on wheat with no "
        f"pathogenicity record, {n_plant} pathogens of other plants, {n_wp} wheat "
        f"pathogens). Crossover is confined to the diagonal blocks: mean crossover between "
        f"congeners is {same_mean:.3f} against {cross_mean:.4f} across genera, so an "
        f"unresolvable read is still resolved to genus. The {len(prob)} of the {n_wp} "
        f"wheat pathogens whose minimizers overlap another taxon's by at least "
        f"{PROBLEM_THRESH:.0%} are highlighted and named in the full caption; they are "
        f"species complexes rather than database errors, and the three wheat rusts "
        f"({', '.join(rusts)}) resolve cleanly. Keyed by crossover_legend.png.",
    ))


if __name__ == "__main__":
    main()
