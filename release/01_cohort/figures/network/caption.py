"""caption.py — write the network caption from the tables themselves.

    python release/01_cohort/figures/network/caption.py
    python release/01_cohort/figures/network/caption.py --declared

Reads  data/outputs/supp_data_s1_studies.tsv, supp_data_s2_cohort.tsv
       data/curation/relations.tsv, screen_fulltext.tsv
Writes network_caption.txt
       network_declared_caption.txt   --declared

Nothing below is prose with numbers typed into it. The narrative is a template and every
figure in it is read at write time, for the reason the crop-map caption records: a
caption hand-patched across a session drifts, and a claim nobody can recompute is one
nobody can check. The numbers come from solve_network's own
Cohort class rather than being counted again here, so the caption cannot disagree
with the figure.
"""

